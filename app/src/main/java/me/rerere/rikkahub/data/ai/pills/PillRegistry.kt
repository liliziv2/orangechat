package me.rerere.rikkahub.data.ai.pills

/**
 * 一颗临时行为药丸。
 *
 * 机制借自 pilulier（github.com/ceshihaox-dotcom/pilulier）：药丸是一段很短的、
 * 由用户手动挑的行为说明，贴在**自己发出去的那条消息**前面，只作用于下一轮生成，
 * 用完即焚。它跟长期记忆是两件事 —— 记忆管「长期记住什么」，药丸管「这一轮怎么回」。
 * 所以它不进人设、不写记忆库、不影响之后的轮次。
 *
 * 正文沿用上游那套写法规矩：写认知层（她在这个场景里经历什么、你站在哪、她的雷区），
 * 不写台词（短词会被逐字搬进回复，下一轮还会自抄）；要能泛化到一类场景，不只治一句话。
 *
 * @property code 稳定编号，不复用。上游改名不改号，这里照做。
 * @property name 用途名，同时是注入块 `[药丸 · 名]` 里的标题。
 * @property text 注入正文，逐字沿用上游当前版本。
 */
data class Pill(
    val code: String,
    val name: String,
    val text: String,
) {
    /**
     * 药盒里给一行提示用。药方正文的第一句固定是「适用场景：…」，
     * 不另外维护一份摘要 —— 两份描述迟早会不一致。
     */
    val whenToUse: String
        get() = text.lineSequence()
            .firstOrNull { it.startsWith(WHEN_TO_USE_PREFIX) }
            ?.removePrefix(WHEN_TO_USE_PREFIX)
            ?.trim()
            .orEmpty()

    private companion object {
        const val WHEN_TO_USE_PREFIX = "适用场景："
    }
}

