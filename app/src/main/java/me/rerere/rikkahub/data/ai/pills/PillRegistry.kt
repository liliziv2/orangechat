    /** 按编号取一颗。旧药丸被删掉时返回 null，调用侧跳过即可，不留崩溃。 */
    fun byCode(code: String): Pill? = byCodeMap[code]

    /** 按给定顺序解析出药丸，未知编号直接跳过。 */
    fun resolve(codes: Collection<String>): List<Pill> = codes.mapNotNull { byCode(it) }
